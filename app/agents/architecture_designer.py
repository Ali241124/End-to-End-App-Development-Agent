"""Architecture Designer for Phase 1.

It consumes the ``intent.json`` generated by the planner and the
``DEVELOPMENT_PLAN.md`` (optional) and produces two artefacts inside the
project folder:

* ``ARCHITECTURE.md`` – a Mermaid flowchart showing Front‑end → API → DB.
* ``models.py`` (only when a relational DB is requested) – a minimal
  SQLAlchemy model stub.
"""

import json
from pathlib import Path


def _load_intent(project_root: Path) -> dict:
    intent_path = project_root / "intent.json"
    if not intent_path.is_file():
        raise FileNotFoundError(f"Intent file not found: {intent_path}")
    return json.loads(intent_path.read_text(encoding="utf-8"))


def _mermaid_diagram(intent: dict) -> str:
    """Return a Mermaid flowchart string.

    The diagram always contains three nodes: **Frontend**, **API**, and the
    chosen **Database**.  It is deliberately simple – later phases can enrich
    it.
    """
    db = intent.get("tech_preferences", {}).get("db", "SQLite")
    diagram = f"""```mermaid\nflowchart LR\n    UI[Frontend] --> API[FastAPI Backend]\n    API --> DB[{db}]\n```"""
    return diagram


def _maybe_generate_models(intent: dict) -> str | None:
    db = intent.get("tech_preferences", {}).get("db", "SQLite").lower()
    if db in {"postgresql", "postgres", "sqlite"}:
        # Very small example model
        return (
            "from sqlalchemy import Column, Integer, String, create_engine, declarative_base\n\n"
            "Base = declarative_base()\n\n"
            "class Item(Base):\n    __tablename__ = 'items'\n    id = Column(Integer, primary_key=True)\n    name = Column(String, nullable=False)\n"
        )
    return None


def design_architecture(project_name: str) -> None:
    """Create architecture artefacts for *project_name*.

    The function is idempotent – re‑running it will overwrite the files with the
    same content.
    """
    project_root = Path("generated_projects") / project_name
    if not project_root.is_dir():
        raise FileNotFoundError(f"Project folder not found: {project_root}")

    intent = _load_intent(project_root)

    # 1️⃣ Write ARCHITECTURE.md
    arch_path = project_root / "ARCHITECTURE.md"
    arch_path.write_text(_mermaid_diagram(intent), encoding="utf-8")

    # 2️⃣ Optionally write models.py
    models_code = _maybe_generate_models(intent)
    if models_code:
        (project_root / "models.py").write_text(models_code, encoding="utf-8")

    print(f"Architecture artefacts written to {project_root}")


if __name__ == "__main__":
    pname = input("Project folder name (no spaces): ")
    design_architecture(pname)

